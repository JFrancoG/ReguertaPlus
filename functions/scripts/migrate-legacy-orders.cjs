function isoWeekMonday(year, week) {
  const januaryFourth = new Date(Date.UTC(year, 0, 4));
  const isoWeekday = januaryFourth.getUTCDay() || 7;
  const monday = new Date(Date.UTC(year, 0, 5 - isoWeekday));
  monday.setUTCDate(monday.getUTCDate() + (week - 1) * 7);
  return monday;
}

function madridOffsetMilliseconds(date) {
  const parts = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Europe/Madrid",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  }).formatToParts(date);
  const values = Object.fromEntries(parts
    .filter((part) => part.type !== "literal")
    .map((part) => [part.type, Number(part.value)]));
  const representedAsUtc = Date.UTC(
    values.year,
    values.month - 1,
    values.day,
    values.hour,
    values.minute,
    values.second,
  );
  return representedAsUtc - date.getTime();
}

function madridDate(year, monthIndex, day, hour) {
  const localAsUtc = Date.UTC(year, monthIndex, day, hour, 0, 0);
  let candidate = new Date(localAsUtc);
  for (let attempt = 0; attempt < 2; attempt += 1) {
    candidate = new Date(
      localAsUtc - madridOffsetMilliseconds(candidate),
    );
  }
  return candidate;
}

function weeklyTimestamps(week) {
  const monday = isoWeekMonday(2026, week);
  const wednesday = new Date(monday);
  wednesday.setUTCDate(wednesday.getUTCDate() + 2);
  const sunday = new Date(monday);
  sunday.setUTCDate(sunday.getUTCDate() + 6);
  const confirmed = madridDate(
    sunday.getUTCFullYear(),
    sunday.getUTCMonth(),
    sunday.getUTCDate(),
    12,
  );
  const delivery = madridDate(
    wednesday.getUTCFullYear(),
    wednesday.getUTCMonth(),
    wednesday.getUTCDate(),
    0,
  );
  return {confirmed, delivery};
}

function sourceYearIsProven(snapshot) {
  if (snapshot.data && hasOwn(snapshot.data, "year")) {
    return snapshot.data.year === 2026;
  }
  const milliseconds = timestampMilliseconds(snapshot.createTime);
  return milliseconds !== null &&
    new Date(milliseconds).getUTCFullYear() === 2026;
}

function metadataToken(value) {
  const components = timestampComponents(value, true);
  if (components) {
    return `${components.seconds}:${components.nanoseconds}`;
  }
  return value === null || value === undefined ? null : String(value);
}

function redactedMigrationError(error) {
  const message = error instanceof Error ? error.message : "";
  const safePatterns = [
    /^Unsupported argument: --[a-z-]+$/,
    /^Duplicate argument: --[a-z-]+$/,
    /^--project with an explicit Firebase project id is required$/,
    /^--target-env must be exactly develop or production$/,
    /^--week must be one ISO week from 2026-W28 through 2026-W34$/,
    /^--apply requires --expected-plan-digest with the dry-run SHA-256 hex digest$/,
    /^--expected-plan-digest is supported only with --apply$/,
    /^Migration options require an explicit boolean apply flag$/,
    /^Migration test hooks require the Firestore emulator$/,
    /^Live migration CLI refuses the Firestore emulator$/,
    /^Live migration project must be exactly reguerta-9f27f$/,
    /^Firestore project does not match the requested project$/,
    /^Malformed legacy-order migration plan$/,
    /^Unsafe legacy-order migration plan: [a-z0-9, -]+$/,
    /^Order group exceeds \d+ Firestore operations$/,
    /^Order group exceeds \d+ guarded reads$/,
    /^Unsupported migration guard$/,
    /^Migration guard changed after planning$/,
    /^Migration guard update time changed after planning$/,
    /^Dry-run plan digest no longer matches; run a new dry-run$/,
    /^Migration read-back still has pending writes$/,
    /^Migration read-back digest differs from the reviewed plan$/,
    /^Migration apply stopped after \d+ successful writes$/,
    /^Migration read-back failed after \d+ successful writes$/,
  ];
  if (safePatterns.some((pattern) => pattern.test(message))) {
    return message;
  }
  const code = error && hasOwn(error, "code") ? String(error.code) : null;
  return code && /^[a-z0-9_-]+$/i.test(code) ?
    `Firestore migration failed with code ${code}` :
    "Firestore migration failed; no raw document details were printed";
}

