function finalizeMigrationDiagnostics(state) {
  const malformedProductOrderlineReasons = [
    ...state.malformedProduct.orderlineReasons.entries(),
  ]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([reason, count]) => ({
      reason,
      count,
      distinctProducts:
        state.malformedProduct.productIdsByReason.get(reason)?.size || 0,
    }));
  const duplicateWeeks = [...state.duplicateOwnerWeek.weeks.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([weekKey, counts]) => ({weekKey, ...counts}));
  const groupSizes = [...state.duplicateOwnerWeek.groupSizes.entries()]
    .sort(([left], [right]) => left - right)
    .map(([size, groups]) => ({size, groups}));
  const orderWithoutOrderlineWeeks = [
    ...state.orderWithoutOrderlines.weeks.entries(),
  ]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([weekKey, week]) => ({
      weekKey,
      orders: week.orders,
      reasons: diagnosticReasonEntries(week.reasons),
    }));
  const emptyLegacyOrderWeeks = [
    ...state.emptyLegacyOrdersSkipped.weeks.entries(),
  ]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([weekKey, orders]) => ({weekKey, orders}));
  return {
    malformedProduct: {
      catalogDocuments: {
        count: diagnosticCountTotal(state.malformedProduct.catalogReasons),
        reasons: diagnosticReasonEntries(
          state.malformedProduct.catalogReasons,
        ),
      },
      affectedOrderlines: {
        count: diagnosticCountTotal(state.malformedProduct.orderlineReasons),
        distinctProducts: state.malformedProduct.productIds.size,
        reasons: malformedProductOrderlineReasons,
      },
    },
    malformedTargetOrder: {
      documents: diagnosticCountTotal(state.malformedTargetOrderReasons),
      reasons: diagnosticReasonEntries(state.malformedTargetOrderReasons),
    },
    canonicalTargetOrdersOutsideSelectedWeek:
      state.canonicalTargetOrdersOutsideSelectedWeek,
    duplicateOwnerWeek: {
      groups: state.duplicateOwnerWeek.groups,
      documents: state.duplicateOwnerWeek.documents,
      groupSizes,
      weeks: duplicateWeeks,
    },
    emptyLegacyOrdersSkipped: {
      orders: state.emptyLegacyOrdersSkipped.orders,
      weeks: emptyLegacyOrderWeeks,
    },
    orderWithoutOrderlines: {
      orders: diagnosticCountTotal(state.orderWithoutOrderlines.reasons),
      reasons: diagnosticReasonEntries(state.orderWithoutOrderlines.reasons),
      weeks: orderWithoutOrderlineWeeks,
    },
  };
}

function parseSourceOrder(snapshot, blockerCounts, selectedWeekKey) {
  if (!sourceYearIsProven(snapshot)) {
    addBlocker(blockerCounts, "source-year-unproven");
    return null;
  }
  const id = validDocumentId(snapshot.id);
  const data = snapshot.data;
  if (!id || !data || typeof data !== "object" || Array.isArray(data)) {
    addBlocker(blockerCounts, "malformed-order");
    return null;
  }
  const userId = validDocumentId(data.userId);
  const name = typeof data.name === "string" ? data.name.trim() : null;
  const surname = typeof data.surname === "string" ? data.surname.trim() : null;
  const week = positiveInteger(data.week);
  const explicitYear = hasOwn(data, "year") ? data.year : 2026;
  const selectedWeek = Number(selectedWeekKey.slice(-2));
  const expectedWeekKey = week === selectedWeek ? selectedWeekKey : null;
  const explicitWeekKeyMatches = !hasOwn(data, "weekKey") ||
    normalizedString(data.weekKey) === expectedWeekKey;
  const displayName = [name, surname].filter(Boolean).join(" ");
  if (
    !userId ||
    name === null ||
    surname === null ||
    !displayName ||
    week !== selectedWeek ||
    explicitYear !== 2026 ||
    !explicitWeekKeyMatches
  ) {
    addBlocker(blockerCounts, "malformed-order");
    return null;
  }
  return {
    id,
    userId,
    displayName,
    week,
    weekKey: weekKeyForWeek(week),
    sourceUpdateTime: snapshot.updateTime ?? null,
    sourceCreateTime: snapshot.createTime,
    sourceData: data,
  };
}

function parseSourceOrderline(snapshot, blockerCounts, selectedWeekKey) {
  if (!sourceYearIsProven(snapshot)) {
    addBlocker(blockerCounts, "source-year-unproven");
    return null;
  }
  const id = validDocumentId(snapshot.id);
  const data = snapshot.data;
  if (!id || !data || typeof data !== "object" || Array.isArray(data)) {
    addBlocker(blockerCounts, "malformed-orderline");
    return null;
  }
  const orderId = validDocumentId(data.orderId);
  const productId = validDocumentId(data.productId);
  const userId = validDocumentId(data.userId);
  const companyName = normalizedString(data.companyName);
  const quantity = positiveInteger(data.quantity);
  const subtotal = nonNegativeNumber(data.subtotal);
  const week = positiveInteger(data.week);
  const explicitYear = hasOwn(data, "year") ? data.year : 2026;
  const selectedWeek = Number(selectedWeekKey.slice(-2));
  const expectedWeekKey = week === selectedWeek ? selectedWeekKey : null;
  const explicitWeekKeyMatches = !hasOwn(data, "weekKey") ||
    normalizedString(data.weekKey) === expectedWeekKey;
  if (
    !orderId ||
    !productId ||
    !userId ||
    !companyName ||
    quantity === null ||
    subtotal === null ||
    week !== selectedWeek ||
    explicitYear !== 2026 ||
    !explicitWeekKeyMatches
  ) {
    addBlocker(blockerCounts, "malformed-orderline");
    return null;
  }
  return {
    id,
    orderId,
    productId,
    userId,
    companyName,
    quantity,
    subtotal,
    week,
    sourceUpdateTime: snapshot.updateTime ?? null,
    sourceCreateTime: snapshot.createTime,
    sourceData: data,
  };
}

function normalizedProductSnapshot(snapshot) {
  const id = validDocumentId(snapshot.id);
  const data = snapshot.data;
  if (!id) {
    return {product: null, diagnosticReason: "invalidCatalogDocumentId"};
  }
  if (!data || typeof data !== "object" || Array.isArray(data)) {
    return {product: null, diagnosticReason: "invalidCatalogDocumentData"};
  }
  return {
    product: {
      id,
      data,
      updateTime: snapshot.updateTime ?? null,
    },
    diagnosticReason: null,
  };
}

function resolveEcoBasketOption(sourceData, productIsEcoBasket, isRenunciation) {
  const canonical = sourceData.ecoBasketOption;
  const alias = sourceData.ecoBasketOptionAtOrder;
  const candidate = canonical === undefined || canonical === null ? alias : canonical;
  if (
    candidate !== undefined &&
    candidate !== null &&
    candidate !== "pickup" &&
    candidate !== "no_pickup"
  ) {
    throw new Error("invalid-eco-basket-option");
  }
  const expected = isRenunciation ?
    "no_pickup" :
    (productIsEcoBasket ? "pickup" : null);
  if (candidate !== undefined && candidate !== null && candidate !== expected) {
    throw new Error("invalid-eco-basket-option");
  }
  return expected;
}

function transformOrderline(line, order, productById) {
  const renunciationProductId = RENUNCIATION_TO_ECO_BASKET_PRODUCT_ID.get(
    line.productId,
  );
  const kiloProductId = HALF_KILO_TO_KILO_PRODUCT_ID.get(line.productId);
  const productId = renunciationProductId || kiloProductId || line.productId;
  const product = productById.get(productId);
  if (!product) {
    throw new Error("missing-product");
  }
  const productData = product.data;
  const vendorId = validDocumentId(productData.vendorId);
  const productName = normalizedString(productData.name);
  const productIsEcoBasket = catalogBoolean(productData, "isEcoBasket", false);
  if (!vendorId) {
    throw malformedProductError(MALFORMED_PRODUCT_FIELD_REASONS.vendorId);
  }
  if (!productName) {
    throw malformedProductError(MALFORMED_PRODUCT_FIELD_REASONS.name);
  }
  const quantity = kiloProductId ? line.quantity / 2 : line.quantity;
  if (!Number.isFinite(quantity) || quantity <= 0) {
    throw new Error("malformed-orderline");
  }
  const priceAtOrder = roundCurrency(
    requiredPositiveCatalogNumber(productData, "price"),
  );
  const rawPricingMode = catalogPricingMode(productData);
  const ecoBasketOption = resolveEcoBasketOption(
    line.sourceData,
    productIsEcoBasket,
    Boolean(renunciationProductId),
  );
  const timestamps = weeklyTimestamps(line.week);

  const data = {
    orderId: line.orderId,
    productId,
    userId: line.userId,
    companyName: line.companyName,
    quantity,
    subtotal: roundCurrency(line.subtotal),
    week: line.week,
    weekKey: order.weekKey,
    consumerDisplayName: order.displayName,
    vendorId,
    ecoBasketOption,
    productName,
    productImageUrl: nullableLegacyImageUrl(productData, line.sourceData),
    priceAtOrder,
    pricingModeAtOrder: rawPricingMode,
    unitName: requiredCatalogString(productData, "unitName"),
    unitPlural: requiredCatalogString(productData, "unitPlural"),
    unitAbbreviation: nullableCatalogString(
      productData,
      "unitAbbreviation",
    ),
    unitQty: requiredPositiveCatalogNumber(productData, "unitQty"),
    createdAt: timestamps.confirmed,
    updatedAt: timestamps.confirmed,
  };
  const optionalPackSnapshot = {
    packContainerName: nullableCatalogString(productData, "packContainerName"),
    packContainerPlural: nullableCatalogString(
      productData,
      "packContainerPlural",
    ),
    packContainerAbbreviation: nullableCatalogString(
      productData,
      "packContainerAbbreviation",
    ),
    packContainerQty: optionalPositiveCatalogNumber(
      productData,
      "packContainerQty",
    ),
  };
  Object.entries(optionalPackSnapshot).forEach(([field, value]) => {
    if (value !== null) {
      data[field] = value;
    }
  });
  const requiredStringFields = [
    "orderId",
    "productId",
    "userId",
    "companyName",
    "weekKey",
    "consumerDisplayName",
    "vendorId",
    "productName",
    "pricingModeAtOrder",
    "unitName",
    "unitPlural",
  ];
  const requiredNumberFields = [
    "quantity",
    "subtotal",
    "week",
    "priceAtOrder",
    "unitQty",
  ];
  if (
    requiredStringFields.some((field) => !normalizedString(data[field])) ||
    requiredNumberFields.some((field) => finiteNumber(data[field]) === null) ||
    ![null, "pickup", "no_pickup"].includes(data.ecoBasketOption)
  ) {
    throw malformedProductError("invalidProjection");
  }
  return {
    data,
    productGuard: {
      kind: "product",
      documentId: productId,
      expectedExists: true,
      updateTime: product.updateTime,
    },
  };
}

function buildOrderData(order, linePayloads) {
  const timestamps = weeklyTimestamps(order.week);
  const total = roundCurrency(linePayloads.reduce(
    (sum, line) => sum + line.data.subtotal,
    0,
  ));
  const totalsByVendor = linePayloads.reduce((totals, line) => {
    const vendorId = line.data.vendorId;
    totals[vendorId] = roundCurrency(
      (totals[vendorId] || 0) + line.data.subtotal,
    );
    return totals;
  }, {});
  return {
    isAutoGenerated: false,
    userId: order.userId,
    consumerDisplayName: order.displayName,
    week: order.week,
    weekKey: order.weekKey,
    consumerStatus: "confirmed",
    producerStatus: "delivered",
    total,
    totalsByVendor,
    createdAt: timestamps.confirmed,
    updatedAt: timestamps.confirmed,
    confirmedAt: timestamps.confirmed,
    deliveryDate: timestamps.delivery,
  };
}

function managedDocumentsEqual(existingData, desiredData, fields) {
  return fields.every((field) => {
    const existingHasField = hasOwn(existingData, field);
    const desiredHasField = hasOwn(desiredData, field);
    return existingHasField === desiredHasField &&
      (!existingHasField || stableStringify(existingData[field]) ===
        stableStringify(desiredData[field]));
  });
}

function documentData(document) {
  return typeof document.data === "function" ? document.data() : document.data;
}

function includeNumericWeekTargetOrder(document, selectedWeekKey) {
  return analyzeTargetOrderBusinessKey(document, selectedWeekKey).scope !==
    "outside";
}

function analyzeTargetOrderBusinessKey(snapshot, selectedWeekKey) {
  const data = documentData(snapshot) || {};
  const userId = validDocumentId(data.userId);
  const memberId = validDocumentId(data.memberId);
  if (userId && memberId && userId !== memberId) {
    return {
      key: null,
      scope: "malformed",
      diagnosticReason: "conflictingOwnerAliases",
    };
  }
  const ownerId = userId || memberId;
  const rawWeekKey = data.weekKey;
  let weekKeyReason = null;
  if (rawWeekKey === undefined || rawWeekKey === null) {
    weekKeyReason = "missingWeekKey";
  } else if (typeof rawWeekKey !== "string") {
    weekKeyReason = "invalidWeekKeyType";
  } else if (
    rawWeekKey !== rawWeekKey.trim() ||
    !CANONICAL_ISO_WEEK_KEY.test(rawWeekKey)
  ) {
    weekKeyReason = "nonCanonicalWeekKey";
  }
  if (!ownerId && weekKeyReason) {
    return {
      key: null,
      scope: "malformed",
      diagnosticReason: "invalidOwnerAndWeekKey",
    };
  }
  if (!ownerId) {
    return {
      key: null,
      scope: "malformed",
      diagnosticReason: "missingOrInvalidOwner",
    };
  }
  if (weekKeyReason) {
    return {key: null, scope: "malformed", diagnosticReason: weekKeyReason};
  }
  const weekKey = rawWeekKey;
  if (hasOwn(data, "week") && data.week !== Number(weekKey.slice(-2))) {
    return {
      key: null,
      scope: "malformed",
      diagnosticReason: "weekValueMismatch",
    };
  }
  if (weekKey !== selectedWeekKey) {
    return {key: null, scope: "outside", diagnosticReason: null};
  }
  return {
    key: `${ownerId}\u0000${weekKey}`,
    scope: "selected",
    diagnosticReason: null,
  };
}

function buildLegacyOrderMigrationPlan({
  sourceOrders,
  sourceOrderLines,
  targetOrders,
  targetOrderLines,
  products,
  weekKey,
  targetEnvironment = "develop",
  projectId = LIVE_PROJECT_ID,
}) {
  if (!ALLOWED_TARGET_ENVIRONMENTS.has(targetEnvironment)) {
    throw new Error("--target-env must be exactly develop or production");
  }
  if (!projectId || !/^[a-z0-9][a-z0-9-]{2,62}$/i.test(projectId)) {
    throw new Error("--project with an explicit Firebase project id is required");
  }
  if (!FIXED_WEEK_KEYS.includes(weekKey)) {
    throw new Error(
      `--week must be one ISO week from ${FIXED_FROM_WEEK} through ${FIXED_TO_WEEK}`,
    );
  }
  const blockerCounts = new Map();
  const diagnosticState = createMigrationDiagnosticState();
  const parsedOrders = (sourceOrders || [])
    .map((snapshot) => parseSourceOrder(snapshot, blockerCounts, weekKey))
    .filter(Boolean);
  const parsedLines = (sourceOrderLines || [])
    .map((snapshot) => parseSourceOrderline(snapshot, blockerCounts, weekKey))
    .filter(Boolean);
  const rawLineCountsByOrderId = new Map();
  (sourceOrderLines || []).forEach((snapshot) => {
    const orderId = validDocumentId(snapshot.data?.orderId);
    if (orderId) {
      addDiagnosticCount(rawLineCountsByOrderId, orderId);
    }
  });
  const productById = new Map();
  (products || []).forEach((snapshot) => {
    const normalized = normalizedProductSnapshot(snapshot);
    if (!normalized.product) {
      addBlocker(blockerCounts, "malformed-product");
      addMalformedProductCatalogDiagnostic(
        diagnosticState,
        normalized.diagnosticReason,
      );
      return;
    }
    const product = normalized.product;
    if (productById.has(product.id)) {
      addBlocker(blockerCounts, "malformed-product");
      addMalformedProductCatalogDiagnostic(
        diagnosticState,
        "duplicateCatalogDocumentId",
      );
      return;
    }
    productById.set(product.id, product);
  });

  const ordersById = new Map(parsedOrders.map((order) => [order.id, order]));
  const ordersByBusinessKey = new Map();
  parsedOrders.forEach((order) => {
    const key = `${order.userId}\u0000${order.weekKey}`;
    const matches = ordersByBusinessKey.get(key) || [];
    matches.push(order);
    ordersByBusinessKey.set(key, matches);
  });
  const emptyDuplicateBusinessKeys = new Set();
  ordersByBusinessKey.forEach((matches, businessKey) => {
    if (matches.length > 1) {
      const allOrdersAreEmptyPlaceholders = matches.every((order) =>
        (rawLineCountsByOrderId.get(order.id) || 0) === 0
      );
      if (allOrdersAreEmptyPlaceholders) {
        emptyDuplicateBusinessKeys.add(businessKey);
        return;
      }
      addBlocker(blockerCounts, "duplicate-owner-week", matches.length);
      addDuplicateOwnerWeekDiagnostic(
        diagnosticState,
        matches[0].weekKey,
        matches.length,
      );
    }
  });

  const linesByOrderId = new Map();
  const parsedLinesByOrderId = new Map();
  parsedLines.forEach((line) => {
    const parsedMatches = parsedLinesByOrderId.get(line.orderId) || [];
    parsedMatches.push(line);
    parsedLinesByOrderId.set(line.orderId, parsedMatches);
    const order = ordersById.get(line.orderId);
    if (!order) {
      addBlocker(blockerCounts, "orphan-orderline");
      return;
    }
    if (line.userId !== order.userId || line.week !== order.week) {
      addBlocker(blockerCounts, "orderline-user-mismatch");
      return;
    }
    const lines = linesByOrderId.get(line.orderId) || [];
    lines.push(line);
    linesByOrderId.set(line.orderId, lines);
  });

  const targetOrdersById = new Map((targetOrders || []).map((snapshot) => [
    snapshot.id,
    snapshot,
  ]));
  const targetOrdersByBusinessKey = new Map();
  (targetOrders || []).forEach((snapshot) => {
    const analysis = analyzeTargetOrderBusinessKey(snapshot, weekKey);
    if (analysis.scope === "outside") {
      diagnosticState.canonicalTargetOrdersOutsideSelectedWeek += 1;
      return;
    }
    if (analysis.scope === "malformed") {
      addBlocker(blockerCounts, "malformed-target-order");
      addMalformedTargetOrderDiagnostic(
        diagnosticState,
        analysis.diagnosticReason,
      );
      return;
    }
    const matches = targetOrdersByBusinessKey.get(analysis.key) || [];
    matches.push(snapshot);
    targetOrdersByBusinessKey.set(analysis.key, matches);
  });
  targetOrdersByBusinessKey.forEach((matches) => {
    if (matches.length > 1) {
      addBlocker(blockerCounts, "target-divergence", matches.length);
    }
  });
  const targetLinesById = new Map((targetOrderLines || []).map((snapshot) => [
    snapshot.id,
    snapshot,
  ]));
  const targetLinesByOrderId = new Map();
  (targetOrderLines || []).forEach((snapshot) => {
    const orderId = validDocumentId(snapshot.data?.orderId);
    const userId = validDocumentId(snapshot.data?.userId);
    const memberId = validDocumentId(snapshot.data?.memberId);
    if (!orderId || (userId && memberId && userId !== memberId)) {
      addBlocker(blockerCounts, "malformed-target-orderline");
      return;
    }
    const matches = targetLinesByOrderId.get(orderId) || [];
    matches.push(snapshot);
    targetLinesByOrderId.set(orderId, matches);
  });

  const groups = [];
  const skippedEmptyOrders = [];
  parsedOrders
    .slice()
    .sort((left, right) =>
      left.weekKey.localeCompare(right.weekKey) || left.id.localeCompare(right.id)
    )
    .forEach((order) => {
      const businessKey = `${order.userId}\u0000${order.weekKey}`;
      const businessOrders = ordersByBusinessKey.get(businessKey) || [];
      const isAllowedEmptyDuplicate = businessOrders.length > 1 &&
        emptyDuplicateBusinessKeys.has(businessKey);
      if (businessOrders.length !== 1 && !isAllowedEmptyDuplicate) {
        return;
      }
      const lines = (linesByOrderId.get(order.id) || [])
        .slice()
        .sort((left, right) => left.id.localeCompare(right.id));
      if (lines.length === 0) {
        const rawLineCount = rawLineCountsByOrderId.get(order.id) || 0;
        if (rawLineCount === 0) {
          const sameBusinessTarget = targetOrdersByBusinessKey.get(
            businessKey,
          ) || [];
          const hasTargetConflict = sameBusinessTarget.length > 0 ||
            targetOrdersById.has(order.id) ||
            (targetLinesByOrderId.get(order.id) || []).length > 0;
          if (hasTargetConflict) {
            addBlocker(blockerCounts, "target-divergence");
          }
          addEmptyLegacyOrderSkippedDiagnostic(
            diagnosticState,
            order.weekKey,
          );
          skippedEmptyOrders.push({
            orderId: order.id,
            userId: order.userId,
            week: order.week,
            weekKey: order.weekKey,
            sourceUpdateTime: order.sourceUpdateTime,
          });
          return;
        }
        addBlocker(blockerCounts, "order-without-orderlines");
        const parsedLineCount = (parsedLinesByOrderId.get(order.id) || []).length;
        addOrderWithoutOrderlinesDiagnostic(
          diagnosticState,
          order.weekKey,
          orderWithoutOrderlinesDiagnosticReason(
            rawLineCount,
            parsedLineCount,
          ),
        );
        return;
      }
      const linePayloads = [];
      let transformationFailed = false;
      lines.forEach((line) => {
        try {
          linePayloads.push({
            line,
            ...transformOrderline(line, order, productById),
          });
        } catch (error) {
          transformationFailed = true;
          const candidate = error instanceof Error ? error.message : null;
          const code = TRANSFORMATION_BLOCKER_CODES.has(candidate) ?
            candidate : "malformed-orderline";
          addBlocker(blockerCounts, code);
          if (code === "malformed-product") {
            const productId = RENUNCIATION_TO_ECO_BASKET_PRODUCT_ID.get(
              line.productId,
            ) || HALF_KILO_TO_KILO_PRODUCT_ID.get(line.productId) ||
              line.productId;
            addMalformedProductOrderlineDiagnostic(
              diagnosticState,
              error,
              productId,
            );
          }
        }
      });
      if (transformationFailed) {
        return;
      }

      const desiredOrderData = buildOrderData(order, linePayloads);
      const desiredLineIds = new Set(linePayloads.map(({line}) => line.id));
      const writes = [];
      const guards = [
        {
          kind: "source-order",
          documentId: order.id,
          expectedExists: true,
          updateTime: order.sourceUpdateTime,
        },
      ];
      lines.forEach((line) => guards.push({
        kind: "source-orderline",
        documentId: line.id,
        expectedExists: true,
        updateTime: line.sourceUpdateTime,
      }));
      const productGuards = new Map();
      linePayloads.forEach(({productGuard}) => {
        productGuards.set(productGuard.documentId, productGuard);
      });
      guards.push(...productGuards.values());

      const sameBusinessTarget = targetOrdersByBusinessKey.get(businessKey) || [];
      if (
        sameBusinessTarget.length === 1 &&
        sameBusinessTarget[0].id !== order.id
      ) {
        addBlocker(blockerCounts, "target-divergence");
      }
      const targetOrder = targetOrdersById.get(order.id);
      if (targetOrder) {
        guards.push({
          kind: "target-order",
          documentId: order.id,
          expectedExists: true,
          updateTime: targetOrder.updateTime ?? null,
        });
        if (!managedDocumentsEqual(
          targetOrder.data,
          desiredOrderData,
          ORDER_MANAGED_FIELDS,
        )) {
          addBlocker(blockerCounts, "target-divergence");
        }
      } else {
        guards.push({
          kind: "target-order",
          documentId: order.id,
          expectedExists: false,
          updateTime: null,
        });
        writes.push({
          operation: "create",
          collection: TARGET_ORDERS_COLLECTION,
          documentId: order.id,
          data: desiredOrderData,
          sourceUpdateTime: order.sourceUpdateTime,
          targetUpdateTime: null,
        });
      }

      linePayloads.forEach(({line, data}) => {
        const targetLine = targetLinesById.get(line.id);
        if (targetLine) {
          guards.push({
            kind: "target-orderline",
            documentId: line.id,
            expectedExists: true,
            updateTime: targetLine.updateTime ?? null,
          });
          if (
            hasOwn(targetLine.data || {}, "ecoBasketOptionAtOrder") ||
            !managedDocumentsEqual(
              targetLine.data,
              data,
              ORDERLINE_MANAGED_FIELDS,
            )
          ) {
            addBlocker(blockerCounts, "target-divergence");
          }
        } else {
          guards.push({
            kind: "target-orderline",
            documentId: line.id,
            expectedExists: false,
            updateTime: null,
          });
          writes.push({
            operation: "create",
            collection: TARGET_ORDERLINES_COLLECTION,
            documentId: line.id,
            data,
            sourceUpdateTime: line.sourceUpdateTime,
            targetUpdateTime: null,
          });
        }
      });

      (targetLinesByOrderId.get(order.id) || []).forEach((targetLine) => {
        if (!desiredLineIds.has(targetLine.id)) {
          addBlocker(blockerCounts, "target-divergence");
        }
      });

      groups.push({
        orderId: order.id,
        weekKey: order.weekKey,
        projection: {
          order: {documentId: order.id, data: desiredOrderData},
          orderlines: linePayloads.map(({line, data}) => ({
            documentId: line.id,
            data,
          })),
        },
        writes: writes.sort((left, right) =>
          left.collection.localeCompare(right.collection) ||
          left.documentId.localeCompare(right.documentId)
        ),
        guards: guards.sort((left, right) =>
          left.kind.localeCompare(right.kind) ||
          left.documentId.localeCompare(right.documentId)
        ),
      });
    });

  const blockers = Array.from(blockerCounts.entries())
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([code, count]) => ({code, count}));
  const diagnostics = finalizeMigrationDiagnostics(diagnosticState);
  const plannedWrites = groups.reduce(
    (total, group) => total + group.writes.length,
    0,
  );
  const counts = {
    sourceOrdersScanned: (sourceOrders || []).length,
    sourceOrderlinesScanned: (sourceOrderLines || []).length,
    productsScanned: (products || []).length,
    targetOrdersScanned: (targetOrders || []).length,
    targetOrderlinesScanned: (targetOrderLines || []).length,
    plannedGroups: groups.filter((group) => group.writes.length > 0).length,
    plannedOrderCreates: groups.reduce((total, group) =>
      total + group.writes.filter((write) => write.collection === "orders").length,
    0),
    plannedOrderlineCreates: groups.reduce((total, group) =>
      total + group.writes.filter((write) => write.collection === "orderlines").length,
    0),
    plannedWrites,
    blockerCount: blockers.reduce((total, blocker) => total + blocker.count, 0),
  };
  const selectedWeek = Number(weekKey.slice(-2));
  const weekGroups = groups.filter((group) => group.weekKey === weekKey);
  const weeks = {
    [weekKey]: {
      sourceOrders: (sourceOrders || []).filter((document) =>
        document.data?.week === selectedWeek
      ).length,
      sourceOrderlines: (sourceOrderLines || []).filter((document) =>
        document.data?.week === selectedWeek
      ).length,
      targetOrders: (targetOrders || []).filter((document) =>
        document.data?.weekKey === weekKey
      ).length,
      targetOrderlines: (targetOrderLines || []).filter((document) =>
        document.data?.weekKey === weekKey
      ).length,
      plannedGroups: weekGroups.filter((group) => group.writes.length > 0).length,
      plannedOrderCreates: weekGroups.reduce((total, group) =>
        total + group.writes.filter((write) => write.collection === "orders").length,
      0),
      plannedOrderlineCreates: weekGroups.reduce((total, group) =>
        total + group.writes.filter((write) => write.collection === "orderlines").length,
      0),
    },
  };
  return {
    scope: {
      projectId,
      sourceEnvironment: SOURCE_ENVIRONMENT,
      sourceNamespace: SOURCE_NAMESPACE,
      targetEnvironment,
      targetNamespace: TARGET_NAMESPACE,
      weekKey,
    },
    groups,
    skippedEmptyOrders: skippedEmptyOrders.sort((left, right) =>
      left.weekKey.localeCompare(right.weekKey) ||
      left.orderId.localeCompare(right.orderId)
    ),
    blockers,
    counts,
    diagnostics,
    weeks,
  };
}

function assertSafeLegacyOrderMigrationPlan(plan) {
  if (
    !plan ||
    !Array.isArray(plan.blockers) ||
    !Array.isArray(plan.groups) ||
    !Array.isArray(plan.skippedEmptyOrders)
  ) {
    throw new Error("Malformed legacy-order migration plan");
  }
  if (plan.blockers.length > 0) {
    throw new Error(
      "Unsafe legacy-order migration plan: " +
      plan.blockers.map((blocker) => blocker.code).join(", "),
    );
  }
  plan.groups.forEach((group) => {
    if (group.writes.length > MAX_TRANSACTION_WRITES) {
      throw new Error(
        `Order group exceeds ${MAX_TRANSACTION_WRITES} Firestore operations`,
      );
    }
    if (group.guards.length > MAX_TRANSACTION_GUARDS) {
      throw new Error(
        `Order group exceeds ${MAX_TRANSACTION_GUARDS} guarded reads`,
      );
    }
  });
  skippedEmptyOrderGroups(plan.skippedEmptyOrders).forEach((orders) => {
    const guardedReads = orders.length * 4 + 5;
    if (guardedReads > MAX_TRANSACTION_GUARDS) {
      throw new Error(
        `Empty-cart group exceeds ${MAX_TRANSACTION_GUARDS} guarded reads`,
      );
    }
  });
}

function computeLegacyOrderMigrationDigest(plan) {
  const digestInput = {
    scope: plan.scope,
    blockers: plan.blockers,
    skippedEmptyOrders: plan.skippedEmptyOrders,
    groups: plan.groups
      .slice()
      .sort((left, right) =>
        left.weekKey.localeCompare(right.weekKey) ||
        left.orderId.localeCompare(right.orderId)
      )
      .map((group) => ({
        orderId: group.orderId,
        weekKey: group.weekKey,
        projection: group.projection,
        writes: group.writes,
        guards: group.guards,
      })),
  };
  return createHash("sha256").update(stableStringify(digestInput)).digest("hex");
}

function computeLegacySourceDigest(plan) {
  const sourceEvidence = plan.groups
    .flatMap((group) => group.guards)
    .filter((guard) => [
      "source-order",
      "source-orderline",
      "product",
    ].includes(guard.kind))
    .map((guard) => ({
      kind: guard.kind,
      documentId: guard.documentId,
      updateTime: guard.updateTime,
    }))
    .concat(plan.skippedEmptyOrders.map((order) => ({
      kind: "empty-source-order",
      documentId: order.orderId,
      updateTime: order.sourceUpdateTime,
    })))
    .sort((left, right) =>
      left.kind.localeCompare(right.kind) ||
      left.documentId.localeCompare(right.documentId)
    );
  return createHash("sha256")
    .update(stableStringify(sourceEvidence))
    .digest("hex");
}

function computeLegacyProjectionDigest(plan) {
  const projection = plan.groups
    .map((group) => ({
      orderId: group.orderId,
      weekKey: group.weekKey,
      projection: group.projection,
    }))
    .sort((left, right) =>
      left.weekKey.localeCompare(right.weekKey) ||
      left.orderId.localeCompare(right.orderId)
    );
  return createHash("sha256")
    .update(stableStringify(projection))
    .digest("hex");
}

function snapshotRecord(snapshot) {
  return {
    id: snapshot.id,
    data: snapshot.data(),
    createTime: snapshot.createTime,
    updateTime: snapshot.updateTime,
  };
}

async function listQueryDocuments(query, pageSize = PAGE_SIZE) {
  const documents = [];
  let cursor = null;
  while (true) {
    let pageQuery = query
      .orderBy(FieldPath.documentId())
      .limit(pageSize);
    if (cursor) {
      pageQuery = pageQuery.startAfter(cursor);
    }
    const snapshot = await pageQuery.get();
    documents.push(...snapshot.docs.map(snapshotRecord));
    if (snapshot.size < pageSize) {
      return documents;
    }
    cursor = snapshot.docs.at(-1);
  }
}

async function loadFieldDocuments(collection, field, values) {
  const uniqueValues = [...new Set(values)].filter((value) =>
    value !== null && value !== undefined
  );
  const documents = [];
  for (let index = 0; index < uniqueValues.length; index += 20) {
    const pages = await Promise.all(uniqueValues.slice(index, index + 20)
      .map((value) => listQueryDocuments(collection.where(field, "==", value))));
    documents.push(...pages.flat());
  }
  return documents;
}

async function loadExactDocuments(firestore, collectionPath, documentIds) {
  const uniqueIds = [...new Set(documentIds.filter(validDocumentId))].sort();
  const documents = [];
  for (let index = 0; index < uniqueIds.length; index += 100) {
    const references = uniqueIds
      .slice(index, index + 100)
      .map((documentId) => firestore.doc(`${collectionPath}/${documentId}`));
    const snapshots = await firestore.getAll(...references);
    documents.push(...snapshots.filter((snapshot) => snapshot.exists)
      .map(snapshotRecord));
  }
  return documents;
}

function mergeDocumentRecords(...recordGroups) {
  const recordsById = new Map();
  recordGroups.flat().forEach((record) => recordsById.set(record.id, record));
  return [...recordsById.values()].sort((left, right) =>
    left.id.localeCompare(right.id)
  );
}

async function loadMigrationInventory(firestore, targetEnvironment, weekKey) {
  const sourceRoot = `${SOURCE_ENVIRONMENT}/${SOURCE_NAMESPACE}`;
  const productRoot = `${SOURCE_ENVIRONMENT}/${TARGET_NAMESPACE}`;
  const targetRoot = `${targetEnvironment}/${TARGET_NAMESPACE}`;
  const weekNumbers = [Number(weekKey.slice(-2))];
  const [sourceOrders, sourceLinesByWeek, products] = await Promise.all([
    loadFieldDocuments(
      firestore.collection(`${sourceRoot}/${SOURCE_ORDERS_COLLECTION}`),
      "week",
      weekNumbers,
    ),
    loadFieldDocuments(
      firestore.collection(`${sourceRoot}/${SOURCE_ORDERLINES_COLLECTION}`),
      "week",
      weekNumbers,
    ),
    listQueryDocuments(
      firestore.collection(`${productRoot}/${PRODUCT_COLLECTION}`),
    ),
  ]);
  const sourceLinesByOrderId = await loadFieldDocuments(
    firestore.collection(`${sourceRoot}/${SOURCE_ORDERLINES_COLLECTION}`),
    "orderId",
    sourceOrders.map((document) => document.id),
  );
  const sourceOrderLines = mergeDocumentRecords(
    sourceLinesByWeek,
    sourceLinesByOrderId,
  );
  const targetOrdersPath = `${targetRoot}/${TARGET_ORDERS_COLLECTION}`;
  const targetOrderlinesPath = `${targetRoot}/${TARGET_ORDERLINES_COLLECTION}`;
  const [targetOrdersByWeekKey, targetOrdersByWeek, targetLinesByWeekKey,
    targetLinesByOrderId, exactTargetOrders, exactTargetOrderLines] =
    await Promise.all([
      loadFieldDocuments(
      firestore.collection(targetOrdersPath),
      "weekKey",
      [weekKey],
    ),
      loadFieldDocuments(
        firestore.collection(targetOrdersPath),
        "week",
        weekNumbers,
      ),
      loadFieldDocuments(
      firestore.collection(targetOrderlinesPath),
      "weekKey",
      [weekKey],
    ),
      loadFieldDocuments(
        firestore.collection(targetOrderlinesPath),
        "orderId",
        sourceOrders.map((document) => document.id),
      ),
      loadExactDocuments(
      firestore,
      targetOrdersPath,
      sourceOrders.map((document) => document.id),
    ),
      loadExactDocuments(
      firestore,
      targetOrderlinesPath,
      sourceOrderLines.map((document) => document.id),
    ),
    ]);
  const targetOrders = mergeDocumentRecords(
    targetOrdersByWeekKey,
    targetOrdersByWeek,
    exactTargetOrders,
  );
  const targetOrderLines = mergeDocumentRecords(
    targetLinesByWeekKey,
    targetLinesByOrderId,
    exactTargetOrderLines,
  );
  return {
    sourceOrders,
    sourceOrderLines,
    products,
    targetOrders,
    targetOrderLines,
  };
}

function guardPath(guard, targetEnvironment) {
  const sourceRoot = `${SOURCE_ENVIRONMENT}/${SOURCE_NAMESPACE}`;
  const productRoot = `${SOURCE_ENVIRONMENT}/${TARGET_NAMESPACE}`;
  const targetRoot = `${targetEnvironment}/${TARGET_NAMESPACE}`;
  switch (guard.kind) {
  case "source-order":
    return `${sourceRoot}/${SOURCE_ORDERS_COLLECTION}/${guard.documentId}`;
  case "source-orderline":
    return `${sourceRoot}/${SOURCE_ORDERLINES_COLLECTION}/${guard.documentId}`;
  case "product":
    return `${productRoot}/${PRODUCT_COLLECTION}/${guard.documentId}`;
  case "target-order":
    return `${targetRoot}/${TARGET_ORDERS_COLLECTION}/${guard.documentId}`;
  case "target-orderline":
    return `${targetRoot}/${TARGET_ORDERLINES_COLLECTION}/${guard.documentId}`;
  default:
    throw new Error("Unsupported migration guard");
  }
}

function writePath(write, targetEnvironment) {
  const targetRoot = `${targetEnvironment}/${TARGET_NAMESPACE}`;
  return `${targetRoot}/${write.collection}/${write.documentId}`;
}

function assertQueryMembership(documents, guards, kind) {
  const actualById = new Map(documents.map((document) => [document.id, document]));
  const expected = guards.filter((guard) =>
    guard.kind === kind && guard.expectedExists
  );
  if (
    actualById.size !== expected.length ||
    expected.some((guard) => !actualById.has(guard.documentId))
  ) {
    throw new Error("Migration guard changed after planning");
  }
  expected.forEach((guard) => {
    const document = actualById.get(guard.documentId);
    if (metadataToken(document.updateTime) !== metadataToken(guard.updateTime)) {
      throw new Error("Migration guard update time changed after planning");
    }
  });
}

function mergeQuerySnapshots(...snapshots) {
  const documentsById = new Map();
  snapshots.forEach((snapshot) => snapshot.docs.forEach((document) => {
    documentsById.set(document.id, document);
  }));
  return [...documentsById.values()];
}

function skippedEmptyOrderGroups(orders) {
  const groupsByBusinessKey = new Map();
  orders.forEach((order) => {
    const businessKey = `${order.userId}\u0000${order.weekKey}`;
    const group = groupsByBusinessKey.get(businessKey) || [];
    group.push(order);
    groupsByBusinessKey.set(businessKey, group);
  });
  return [...groupsByBusinessKey.values()]
    .map((group) => group.sort((left, right) =>
      left.orderId.localeCompare(right.orderId)
    ))
    .sort((left, right) =>
      left[0].weekKey.localeCompare(right[0].weekKey) ||
      left[0].userId.localeCompare(right[0].userId)
    );
}

async function guardSkippedEmptyOrderGroup(
  firestore,
  targetEnvironment,
  orders,
) {
  return firestore.runTransaction(async (transaction) => {
    const sourceRoot = `${SOURCE_ENVIRONMENT}/${SOURCE_NAMESPACE}`;
    const targetRoot = `${targetEnvironment}/${TARGET_NAMESPACE}`;
    const representative = orders[0];
    const pointReferences = orders.flatMap((order) => [
      firestore.doc(
        `${sourceRoot}/${SOURCE_ORDERS_COLLECTION}/${order.orderId}`,
      ),
      firestore.doc(
        `${targetRoot}/${TARGET_ORDERS_COLLECTION}/${order.orderId}`,
      ),
    ]);
    const [pointSnapshots, sourceOrders, sourceOrderlineSnapshots,
      targetOrdersByUserAndWeekKey, targetOrdersByMemberAndWeekKey,
      targetOrdersByUserAndWeek, targetOrdersByMemberAndWeek,
      targetOrderlineSnapshots] =
      await Promise.all([
        transaction.getAll(...pointReferences),
        transaction.get(firestore
          .collection(`${sourceRoot}/${SOURCE_ORDERS_COLLECTION}`)
          .where("userId", "==", representative.userId)
          .where("week", "==", representative.week)),
        Promise.all(orders.map((order) => transaction.get(firestore
          .collection(`${sourceRoot}/${SOURCE_ORDERLINES_COLLECTION}`)
          .where("orderId", "==", order.orderId)))),
        transaction.get(firestore
          .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
          .where("userId", "==", representative.userId)
          .where("weekKey", "==", representative.weekKey)),
        transaction.get(firestore
          .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
          .where("memberId", "==", representative.userId)
          .where("weekKey", "==", representative.weekKey)),
        transaction.get(firestore
          .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
          .where("userId", "==", representative.userId)
          .where("week", "==", representative.week)),
        transaction.get(firestore
          .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
          .where("memberId", "==", representative.userId)
          .where("week", "==", representative.week)),
        Promise.all(orders.map((order) => transaction.get(firestore
          .collection(`${targetRoot}/${TARGET_ORDERLINES_COLLECTION}`)
          .where("orderId", "==", order.orderId)))),
      ]);
    orders.forEach((order, index) => {
      const sourceOrder = pointSnapshots[index * 2];
      const targetOrder = pointSnapshots[index * 2 + 1];
      if (
        !sourceOrder.exists ||
        metadataToken(sourceOrder.updateTime) !==
          metadataToken(order.sourceUpdateTime) ||
        targetOrder.exists
      ) {
        throw new Error("Migration guard changed after planning");
      }
      assertQueryMembership(
        sourceOrderlineSnapshots[index].docs,
        [],
        "source-orderline",
      );
      assertQueryMembership(
        targetOrderlineSnapshots[index].docs,
        [],
        "target-orderline",
      );
    });
    assertQueryMembership(sourceOrders.docs, orders.map((sourceOrder) => ({
      kind: "source-order",
      documentId: sourceOrder.orderId,
      expectedExists: true,
      updateTime: sourceOrder.sourceUpdateTime,
    })), "source-order");
    const relevantTargetOrders = mergeQuerySnapshots(
      targetOrdersByUserAndWeekKey,
      targetOrdersByMemberAndWeekKey,
      targetOrdersByUserAndWeek,
      targetOrdersByMemberAndWeek,
    ).filter((document) =>
      includeNumericWeekTargetOrder(document, representative.weekKey)
    );
    assertQueryMembership(relevantTargetOrders, [], "target-order");
  });
}

async function applyMigrationGroup(firestore, targetEnvironment, group) {
  if (group.writes.length === 0) {
    return 0;
  }
  return firestore.runTransaction(async (transaction) => {
    const pointGuards = group.guards.filter((guard) => ![
      "source-orderline",
      "target-orderline",
    ].includes(guard.kind));
    const guardReferences = pointGuards.map((guard) =>
      firestore.doc(guardPath(guard, targetEnvironment))
    );
    const sourceRoot = `${SOURCE_ENVIRONMENT}/${SOURCE_NAMESPACE}`;
    const targetRoot = `${targetEnvironment}/${TARGET_NAMESPACE}`;
    const orderData = group.projection.order.data;
    const [guardSnapshots, sourceOrders, sourceOrderlines,
      targetOrdersByUserAndWeekKey, targetOrdersByMemberAndWeekKey,
      targetOrdersByUserAndWeek, targetOrdersByMemberAndWeek, targetOrderlines] =
      await Promise.all([
      transaction.getAll(...guardReferences),
      transaction.get(firestore
        .collection(`${sourceRoot}/${SOURCE_ORDERS_COLLECTION}`)
        .where("userId", "==", orderData.userId)
        .where("week", "==", orderData.week)),
      transaction.get(firestore
        .collection(`${sourceRoot}/${SOURCE_ORDERLINES_COLLECTION}`)
        .where("orderId", "==", group.orderId)),
      transaction.get(firestore
        .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
        .where("userId", "==", orderData.userId)
        .where("weekKey", "==", group.weekKey)),
      transaction.get(firestore
        .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
        .where("memberId", "==", orderData.userId)
        .where("weekKey", "==", group.weekKey)),
      transaction.get(firestore
        .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
        .where("userId", "==", orderData.userId)
        .where("week", "==", orderData.week)),
      transaction.get(firestore
        .collection(`${targetRoot}/${TARGET_ORDERS_COLLECTION}`)
        .where("memberId", "==", orderData.userId)
        .where("week", "==", orderData.week)),
      transaction.get(firestore
        .collection(`${targetRoot}/${TARGET_ORDERLINES_COLLECTION}`)
        .where("orderId", "==", group.orderId)),
    ]);
    guardSnapshots.forEach((snapshot, index) => {
      const guard = pointGuards[index];
      if (snapshot.exists !== guard.expectedExists) {
        throw new Error("Migration guard changed after planning");
      }
      if (
        snapshot.exists &&
        metadataToken(snapshot.updateTime) !== metadataToken(guard.updateTime)
      ) {
        throw new Error("Migration guard update time changed after planning");
      }
    });
    assertQueryMembership(
      sourceOrders.docs,
      group.guards,
      "source-order",
    );
    assertQueryMembership(
      sourceOrderlines.docs,
      group.guards,
      "source-orderline",
    );
    const relevantTargetOrders = mergeQuerySnapshots(
      targetOrdersByUserAndWeekKey,
      targetOrdersByMemberAndWeekKey,
      targetOrdersByUserAndWeek,
      targetOrdersByMemberAndWeek,
    ).filter((document) =>
      includeNumericWeekTargetOrder(document, group.weekKey)
    );
    assertQueryMembership(
      relevantTargetOrders,
      group.guards,
      "target-order",
    );
    assertQueryMembership(
      targetOrderlines.docs,
      group.guards,
      "target-orderline",
    );
    group.writes.forEach((write) => {
      transaction.create(
        firestore.doc(writePath(write, targetEnvironment)),
        write.data,
      );
    });
    return group.writes.length;
  });
}

function redactedPlanSummary(plan, digest) {
  return {
    scope: plan.scope,
    planDigest: digest,
    sourceDigest: computeLegacySourceDigest(plan),
    projectionDigest: computeLegacyProjectionDigest(plan),
    counts: plan.counts,
    blockers: plan.blockers,
    diagnostics: plan.diagnostics,
    weeks: plan.weeks,
  };
}

async function runLegacyOrderMigration(options, dependencies = {}) {
  const validatedOptions = validateLegacyOrderMigrationOptions(options);
  if (dependencies.testHooks && !process.env.FIRESTORE_EMULATOR_HOST) {
    throw new Error("Migration test hooks require the Firestore emulator");
  }
  const ownsApp = !dependencies.firestore;
  if (ownsApp && process.env.FIRESTORE_EMULATOR_HOST) {
    throw new Error("Live migration CLI refuses the Firestore emulator");
  }
  if (!process.env.FIRESTORE_EMULATOR_HOST && validatedOptions.projectId !== LIVE_PROJECT_ID) {
    throw new Error(`Live migration project must be exactly ${LIVE_PROJECT_ID}`);
  }
  const app = ownsApp ? initializeApp({projectId: validatedOptions.projectId}) : null;
  const firestore = dependencies.firestore || getFirestore(app);
  try {
    const firestoreProjectId = normalizedString(firestore.projectId);
    if (firestoreProjectId && firestoreProjectId !== validatedOptions.projectId) {
      throw new Error("Firestore project does not match the requested project");
    }
    const inventory = await loadMigrationInventory(
      firestore,
      validatedOptions.targetEnvironment,
      validatedOptions.weekKey,
    );
    const plan = buildLegacyOrderMigrationPlan({
      ...inventory,
      weekKey: validatedOptions.weekKey,
      targetEnvironment: validatedOptions.targetEnvironment,
      projectId: validatedOptions.projectId,
    });
    const digest = computeLegacyOrderMigrationDigest(plan);
    const summary = redactedPlanSummary(plan, digest);
    if (!validatedOptions.apply) {
      return {apply: false, ...summary, appliedWrites: 0, readBack: null};
    }
    assertSafeLegacyOrderMigrationPlan(plan);
    if (digest !== validatedOptions.expectedPlanDigest) {
      throw new Error("Dry-run plan digest no longer matches; run a new dry-run");
    }
    if (dependencies.testHooks?.beforeFirstWrite) {
      await dependencies.testHooks.beforeFirstWrite();
    }

    let appliedWrites = 0;
    for (const orders of skippedEmptyOrderGroups(plan.skippedEmptyOrders)) {
      try {
        await guardSkippedEmptyOrderGroup(
          firestore,
          validatedOptions.targetEnvironment,
          orders,
        );
      } catch {
        throw new Error(
          `Migration apply stopped after ${appliedWrites} successful writes`,
        );
      }
    }
    const groupsWithWrites = plan.groups.filter((group) => group.writes.length > 0);
    for (const [index, group] of groupsWithWrites.entries()) {
      try {
        if (dependencies.testHooks?.beforeGroupApply) {
          await dependencies.testHooks.beforeGroupApply(index);
        }
        appliedWrites += await applyMigrationGroup(
          firestore,
          validatedOptions.targetEnvironment,
          group,
        );
      } catch {
        throw new Error(
          `Migration apply stopped after ${appliedWrites} successful writes`,
        );
      }
    }
    let readBackPlan;
    let readBackDigest;
    try {
      if (dependencies.testHooks?.beforeReadBack) {
        await dependencies.testHooks.beforeReadBack();
      }
      const readBackInventory = await loadMigrationInventory(
        firestore,
        validatedOptions.targetEnvironment,
        validatedOptions.weekKey,
      );
      readBackPlan = buildLegacyOrderMigrationPlan({
        ...readBackInventory,
        weekKey: validatedOptions.weekKey,
        targetEnvironment: validatedOptions.targetEnvironment,
        projectId: validatedOptions.projectId,
      });
      assertSafeLegacyOrderMigrationPlan(readBackPlan);
      if (readBackPlan.counts.plannedWrites !== 0) {
        throw new Error("Migration read-back still has pending writes");
      }
      readBackDigest = computeLegacyOrderMigrationDigest(readBackPlan);
      if (
        computeLegacySourceDigest(readBackPlan) !== summary.sourceDigest ||
        computeLegacyProjectionDigest(readBackPlan) !== summary.projectionDigest
      ) {
        throw new Error("Migration read-back digest differs from the reviewed plan");
      }
    } catch {
      throw new Error(
        `Migration read-back failed after ${appliedWrites} successful writes`,
      );
    }
    return {
      apply: true,
      ...summary,
      appliedWrites,
      readBack: redactedPlanSummary(readBackPlan, readBackDigest),
    };
  } finally {
    if (ownsApp) {
      await deleteApp(app);
    }
  }
}

async function main() {
  const options = parseLegacyOrderMigrationArgs(process.argv.slice(2));
  const result = await runLegacyOrderMigration(options);
  console.log(JSON.stringify(result, null, 2));
}

if (require.main === module) {
  main().catch((error) => {
    console.error(redactedMigrationError(error));
    process.exitCode = 1;
  });
}

